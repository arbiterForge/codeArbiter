"""Bounded generated-file publication: stage all bytes, serialize, rollback on failure.

A surviving lock is an explicit unusable-output marker (including process death).
Never delete it automatically: its journal and backups are recovery evidence.
"""
from pathlib import Path
import json
import os
import shutil
import stat
import tempfile


def assert_complete(root, namespace):
    markers = list(Path(root).glob(".generated-*.lock"))
    if markers:
        raise OSError(f"incomplete or concurrent generated output ({namespace}): {markers[0]}")


def validate_targets(root, paths):
    root = Path(os.path.abspath(root))
    for path in paths:
        _target(root, path)


def _guard_ancestors(path):
    cursor = Path(path)
    while True:
        try:
            info = cursor.lstat()
        except FileNotFoundError:
            info = None
        if info is not None and (stat.S_ISLNK(info.st_mode) or
                getattr(info, "st_file_attributes", 0) & getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400)):
            raise OSError(f"generated target traverses symlink or reparse point: {cursor}")
        parent = cursor.parent
        if parent == cursor:
            return
        cursor = parent


def _target(root, path):
    target = Path(os.path.abspath(path))
    try:
        relative = target.relative_to(root)
    except ValueError:
        raise OSError(f"generated target escapes owner root: {target}") from None
    if not relative.parts:
        raise OSError("generated target cannot replace owner root")
    _guard_ancestors(target)
    if target.exists() and not target.is_file():
        raise OSError(f"generated target is not a regular file: {target}")
    return target


def publish_files(root, namespace, updates, removals=()):
    root = Path(os.path.abspath(root))
    _guard_ancestors(root)
    marker = root / (".generated-" + namespace + ".lock")
    # Exclusive creation serializes writers. A failed exclusive create never
    # removes another writer's marker or journal.
    with marker.open("x", encoding="utf-8") as lock:
        lock.write("publication pending; do not consume generated output\n")
        lock.flush()
        os.fsync(lock.fileno())
    staging = None
    retain = False
    applied = []
    old = {}
    try:
        changes = {_target(root, path): data for path, data in updates.items()}
        deleted = {_target(root, path) for path in removals}
        if deleted & changes.keys():
            raise OSError("generated target both written and removed")
        if any(not isinstance(data, bytes) for data in changes.values()):
            raise TypeError("generated bytes must be fully rendered before publication")
        staging = Path(tempfile.mkdtemp(prefix=".generated-" + namespace + "-", dir=root))
        pending = {}
        for index, target in enumerate(sorted(changes.keys() | deleted)):
            before = target.read_bytes() if target.exists() else None
            old[target] = before
            if before is not None:
                (staging / f"{index}.old").write_bytes(before)
            if target in changes:
                staged = staging / f"{index}.new"
                staged.write_bytes(changes[target])
                if staged.read_bytes() != changes[target]:
                    raise OSError(f"staged byte mismatch: {target}")
                pending[target] = staged
        (staging / "journal.json").write_text(json.dumps([
            {"path": str(path.relative_to(root)), "existed": old[path] is not None}
            for path in sorted(old)], indent=2), encoding="utf-8")
        marker.write_text(str(staging), encoding="utf-8")
        for target in sorted(old):
            _target(root, target)  # recheck immediately before each effect
            target.parent.mkdir(parents=True, exist_ok=True)
            if target in pending:
                os.replace(pending[target], target)
            elif target.exists():
                target.unlink()
            applied.append(target)
        return len(old)
    except BaseException:
        for target in reversed(applied):
            try:
                _target(root, target)
                if old[target] is None:
                    target.unlink(missing_ok=True)
                else:
                    recovery = staging / "rollback"
                    recovery.write_bytes(old[target])
                    os.replace(recovery, target)
            except BaseException:
                retain = True
        raise
    finally:
        if not retain:
            if staging is not None:
                shutil.rmtree(staging)
            marker.unlink()
